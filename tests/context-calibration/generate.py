def utf16_units(text):
    return len(text.encode("utf-16-le")) // 2


def build():
    cases = []
    for family, groups in AUTHORED.items():
        assert set(groups) == {"error", "safe"}
        for kind, texts in groups.items():
            assert len(texts) == 20, (family, kind, len(texts))
            for index, annotated in enumerate(texts, 1):
                markers = list(MARKER.finditer(annotated))
                edits = []
                if kind == "error":
                    assert len(markers) == 1, (family, index)
                    marker = markers[0]
                    original, replacement = marker.groups()
                    assert {original, replacement} == FAMILIES[family]
                    before, after = annotated[:marker.start()], annotated[marker.end():]
                    assert not before or not (before[-1].isalnum() or before[-1] == "_")
                    assert not after or not (after[0].isalnum() or after[0] == "_")
                    text, expected = before + original + after, before + replacement + after
                    edits = [{"offset": utf16_units(before), "length": utf16_units(original),
                              "original": original, "replacement": replacement}]
                else:
                    assert not markers
                    text = expected = annotated
                assert "[[" not in text and "]]" not in text
                identity = f"context-calibration-en-{family}-{kind}-{index:02d}"
                cases.append({"id": identity, "document_id": identity, "language": "en",
                    "source": "localcorrect-context-development-calibration", "split": "development-calibration",
                    "family": family, "kind": kind, "format": "short" if index <= 18 else "email" if index == 19 else "paragraphs",
                    "input": text, "expected": expected, "edits": edits})
    assert len(cases) == 400
    assert len({case["input"] for case in cases}) == len(cases)
    assert len({case["id"] for case in cases}) == len(cases)
    for case in cases:
        restored = case["input"].encode("utf-16-le")
        for edit in reversed(case["edits"]):
            start, end = edit["offset"] * 2, (edit["offset"] + edit["length"]) * 2
            assert restored[start:end].decode("utf-16-le") == edit["original"]
            restored = restored[:start] + edit["replacement"].encode("utf-16-le") + restored[end:]
        assert restored.decode("utf-16-le") == case["expected"]
        assert len(case["edits"]) == (1 if case["kind"] == "error" else 0)
    return {"schemaVersion": 1, "role": "known-development-calibration",
        "language": "en", "provenance": "Hand-authored synthetic prose with explicit word-mutation markers; deterministic rendering only. No model output, existing calibration/test/fresh cases, private chats or source corpora read.",
        "limitations": "Fixed-family, deliberately balanced synthetic calibration data with repeated lexical themes. Not a natural prevalence sample, independent heldout evaluation, fresh audit or neural training data.",
        "cases": cases}


def main():
    payload = build()
    destination = Path(__file__).with_name("cases.json")
    encoded = (json.dumps(payload, ensure_ascii=False, indent=2) + "\n").encode()
    destination.write_bytes(encoded)
    cases = payload["cases"]
    print(json.dumps({"rows": len(cases), "error": sum(c["kind"] == "error" for c in cases),
        "safe": sum(c["kind"] == "safe" for c in cases),
        "formats": {form: sum(c["format"] == form for c in cases) for form in ("short", "email", "paragraphs")},
        "sha256": hashlib.sha256(encoded).hexdigest(), "goldReconstruction": "pass",
        "uniqueInputs": True, "englishOnly": True}))


if __name__ == "__main__":
    main()
