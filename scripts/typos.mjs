// Build-time correction prior. Runtime does no candidate search or training.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import enLexicon from '../packages/core/src/lexicons/en.js';
import * as deAssets from '../packages/core/src/lexicons/de.js';
const lex={en:new Set(enLexicon.split('\n')),de:new Set(deAssets.default.split('\n'))};
const valid=(word,l)=>lex[l].has(word)||lex[l].has(word[0].toUpperCase()+word.slice(1));
const known=word=>valid(word,'en')||valid(word,'de');
const letters=/^\p{Ll}+$/u;
const frequencies=Object.fromEntries(['en','de'].map(l=>[l,new Map(readFileSync(`packages/core/dictionaries/${l}.txt`,'utf8').trim().split('\n').map(line=>{const [w,f]=line.split(' ');return [w,+f];}))]));
const sha=b=>createHash('sha256').update(b).digest('hex');
const sourceRoot='packages/core/vendor/typo-data';
const codespell=readFileSync(`${sourceRoot}/codespell.txt`,'utf8'),litkey=readFileSync(`${sourceRoot}/litkey-pairs.tsv`,'utf8');
const distance=(a,b)=>{let last=Array.from({length:b.length+1},(_,i)=>i),pp;for(let i=1;i<=a.length;i++){let row=[i];for(let j=1;j<=b.length;j++){row[j]=Math.min(row[j-1]+1,last[j]+1,last[j-1]+(a[i-1]===b[j-1]?0:1));if(i>1&&j>1&&a[i-1]===b[j-2]&&a[i-2]===b[j-1])row[j]=Math.min(row[j],pp[j-2]+1);}pp=last;last=row;}return last[b.length];};
// SymSpell symmetric-delete keys find competing common one-edit candidates.
const deletes=w=>new Set([w,...Array.from({length:w.length},(_,i)=>w.slice(0,i)+w.slice(i+1))]);
const summaries={}, output={};
for(const l of ['en','de']){
 const freq=frequencies[l],targets=[...freq.keys()].filter(w=>w.length>=3&&w.length<=24&&freq.get(w)>=150&&valid(w,l));
 const index=new Map();for(const w of targets)for(const k of deletes(w)){if(!index.has(k))index.set(k,[]);index.get(k).push(w);}
 const surfaces=new Map(),attested=new Map(),surfaceKinds=new Map();
 const add=(a,b,kind)=>{
  if(a===b||a.length<3||a.length>24||!letters.test(a)||!letters.test(b)||known(a))return;
  if(kind==='strong'||kind==='omission'){if(!surfaces.has(a))surfaces.set(a,new Set());surfaces.get(a).add(b);if(!surfaceKinds.has(a)||kind==='strong')surfaceKinds.set(a,kind);}
  else {if(!attested.has(a))attested.set(a,new Set());attested.get(a).add(b);}
 };
 for(const w of targets)for(let i=0;i<w.length;i++){
  if(w.length>=6)add(w.slice(0,i)+w.slice(i+1),w,'omission');
  if(i+1<w.length&&w[i]!==w[i+1])add(w.slice(0,i)+w[i+1]+w[i]+w.slice(i+2),w,'strong');
  add(w.slice(0,i)+w[i]+w.slice(i),w,'strong');
  if(w[i]===w[i+1])add(w.slice(0,i)+w.slice(i+1),w,'strong');
  if(l==='de'&&'äöü'.includes(w[i]))add(w.slice(0,i)+({ä:'a',ö:'o',ü:'u'})[w[i]]+w.slice(i+1),w,'strong');
 }
 const rows=new Map();
 for(const [a,values] of surfaces){
  if(values.size!==1)continue;const b=[...values][0];
  const candidates=new Set();for(const k of deletes(a))for(const c of index.get(k)||[])if(Math.abs(c.length-a.length)<=1&&distance(a,c)<=1)candidates.add(c);
  if(candidates.size===1&&candidates.has(b))rows.set(a,[b,surfaceKinds.get(a)]);
 }
 const source=l==='en'?codespell.split('\n').flatMap(line=>{const parts=line.split('->');return parts.length===2&&letters.test(parts[1])?[[parts[0],parts[1]]]:[];}):litkey.trim().split('\n').map(line=>line.split('\t').slice(0,2));
 for(const [a,b] of source)if(a.length>=(l==='en'?3:5)&&valid(b,l)&&(freq.get(b)||0)>=(a.length<5?100000:150)&&Math.abs(a.length-b.length)<=2&&distance(a,b)<=2)add(a,b,'attested');
 for(const [a,values] of attested){
  if(values.size!==1){rows.delete(a);continue;}
  const b=[...values][0],selectedDistance=distance(a,b);
  const alternatives=new Set();for(const k of deletes(a))for(const c of index.get(k)||[])if(c!==b&&distance(a,c)<=Math.min(1,selectedDistance))alternatives.add(c);
  // The public label is a prior, not semantic evidence. Do not restore a
  // spelling that has another equally close common interpretation.
  const closedShort=l==='en'&&new Set(['the','and','this','that','with','from','they','your']).has(b)&&a.length===b.length&&
   Array.from({length:a.length-1},(_,i)=>a.slice(0,i)+a[i+1]+a[i]+a.slice(i+2)).includes(b);
  if(alternatives.size&&!closedShort){rows.delete(a);continue;}
  rows.set(a,[b,l==='en'?'codespell':'litkey']);
 }

 const sorted=[...rows].sort(([a],[b])=>a<b?-1:a>b?1:0);
 const shards={};for(const [a,[b,kind]] of sorted){const k=a.slice(0,2);if(!shards[k])shards[k]=[];shards[k].push(`${a}\t${b}\t${kind}`);}
 output[l]=Object.fromEntries(Object.entries(shards).map(([k,lines])=>[k,lines.join('\n')]));
 summaries[l]={targets:targets.length,pairs:rows.size,kinds:Object.fromEntries(['strong','omission','codespell','litkey'].map(k=>[k,sorted.filter(([,v])=>v[1]===k).length])),sha256:sha(JSON.stringify(output[l]))};
}
const asset='// Generated by scripts/typos.mjs. Source data licenses: CC-BY-SA-3.0 and CC-BY-SA-4.0.\n'+Object.entries(output).map(([l,s])=>`export const ${l} = ${JSON.stringify(s)};`).join('\n')+'\n';
writeFileSync('packages/core/src/typos.js',asset);
writeFileSync('typo-sources.json',JSON.stringify({description:'Public typo priors plus unique common one-edit typing repairs. No test corpus is read.',sources:JSON.parse(readFileSync(`${sourceRoot}/provenance.json`)),inputSha256:{codespell:sha(codespell),litkey:sha(litkey)},inventories:summaries,assetSha256:sha(asset)},null,2)+'\n');
console.log(JSON.stringify(summaries,null,2));
