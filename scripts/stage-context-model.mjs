// Copy one completed local experiment into the candidate. Never train or fetch.
import{readFileSync,writeFileSync,copyFileSync,mkdirSync}from'node:fs';
import{resolve}from'node:path';
import{createHash}from'node:crypto';
import assert from'node:assert/strict';
const directory=process.argv[2];
if(!directory)throw new Error('Usage: node scripts/stage-context-model.mjs EXPERIMENT_DIRECTORY');
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const metadataBytes=readFileSync(resolve(directory,'metadata.json')),metadata=JSON.parse(metadataBytes);
assert.equal(metadata.format,'localcorrect-context-encoder-v1');
const modelBytes=readFileSync(resolve(directory,'context-encoder.onnx'));
assert.equal(sha(modelBytes),metadata.modelSha256);assert.equal(modelBytes.length,metadata.modelBytes);
const models='packages/core/models';mkdirSync(models,{recursive:true});
writeFileSync(models+'/context-encoder.onnx',modelBytes);
writeFileSync(models+'/context-encoder-metadata.json',metadataBytes);
copyFileSync(resolve(directory,'parity.json'),models+'/context-encoder-parity.json');
metadata.metadataSha256=sha(metadataBytes);
writeFileSync('packages/core/src/context-encoder-data.js','/* Generated by scripts/stage-context-model.mjs. */\nexport default '+JSON.stringify(metadata)+';\n');
// A newly staged model must earn a policy through independent calibration.
writeFileSync('packages/core/src/context-policy.js','export default '+JSON.stringify({schemaVersion:1,modelSha256:metadata.metadataSha256,onnxSha256:metadata.modelSha256,actions:{}})+';\n');
console.log(JSON.stringify({modelSha256:metadata.modelSha256,metadataSha256:metadata.metadataSha256,bytes:modelBytes.length}));
